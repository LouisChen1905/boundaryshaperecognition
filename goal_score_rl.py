"""Label-reward contextual bandit for safe exploration-goal scoring (NumPy only).

Each labelled map is a one-step episode. There is no invented action-dependent
next map: recorded motion was generated by another policy. Full-information
policy gradients marginalize over the finite safe action set instead of sampling.
"""

import argparse
from dataclasses import asdict
from itertools import islice
import json
import math
from pathlib import Path

import numpy as np

from boundary_exploration import BoundaryExplorer, ExplorationConfig, GoalScoreCandidate


FEATURES = ("log_gain", "priority_fraction", "path_cost", "boundary_distance",
            "visits", "boundary_along_distance", "boundary_across_distance",
            "boundary_parallel_alignment", "boundary_direction_confidence")
MODEL_VERSION = 2


def features(candidate):
    c = candidate
    dx, dy = np.subtract(c.pose[:2], c.robot_pose[:2])
    scale = c.sensor_range
    tangent = c.boundary_tangent
    confidence = c.boundary_direction_confidence if tangent is not None else 0.0
    along = across = alignment = 0.0
    if confidence:
        along = abs(math.cos(tangent)*dx + math.sin(tangent)*dy) / scale
        across = abs(-math.sin(tangent)*dx + math.cos(tangent)*dy) / scale
        alignment = confidence * math.cos(c.pose[2] - tangent) ** 2
    return np.array([math.log1p(c.gain) / 5,
        c.boundary_gain / max(c.gain, 1e-9), c.path_cost / scale,
        c.boundary_distance / scale, c.visits / 3,
        along, across, alignment, confidence]).clip(-5, 5)


def pose_errors(poses, desired):
    poses = np.asarray(poses, dtype=float)
    desired = np.asarray(desired, dtype=float)
    distance = np.linalg.norm(poses[:, :2] - desired[:2], axis=1)
    difference = poses[:, 2] - desired[2]
    return distance, np.abs(np.arctan2(np.sin(difference), np.cos(difference)))


def rewards(poses, desired, position_scale=1.0, yaw_scale=1.0):
    if not all(math.isfinite(v) and v > 0 for v in (position_scale, yaw_scale)):
        raise ValueError("reward scales must be finite and positive")
    distance, yaw = pose_errors(poses, desired)
    return -np.minimum(distance / position_scale, 10) - yaw / yaw_scale


class GoalScorePolicy:
    """Positive multiplicative residual over the existing score.

    Full search matches the training action set, retaining hard boundary priority,
    visit exhaustion, safety and existing goal-hold/refresh behavior.
    """

    full_goal_search = True

    def __init__(self, weights=None):
        self.weights = np.zeros(len(FEATURES)) if weights is None else np.asarray(weights, dtype=float)
        if self.weights.shape != (len(FEATURES),) or not np.isfinite(self.weights).all():
            raise ValueError("invalid policy weights")

    def __call__(self, candidate):
        return candidate.baseline_score * math.exp(float(np.clip(features(candidate) @ self.weights, -8, 8)))

    def save(self, path, metadata=None):
        write_json(path, dict(schema_version=MODEL_VERSION, feature_names=list(FEATURES),
            weights=self.weights.tolist(), full_goal_search=True, metadata=metadata or {}))

    @classmethod
    def load(cls, path):
        record = json.loads(Path(path).read_text(encoding="utf-8"))
        if (record.get("schema_version") != MODEL_VERSION
                or record.get("feature_names") != list(FEATURES)
                or record.get("full_goal_search") is not True):
            raise ValueError("incompatible goal score model")
        return cls(record["weights"])


def write_json(path, record):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(record, ensure_ascii=False, indent=2, allow_nan=False) + "\n",
                         encoding="utf-8")
    temporary.replace(path)


def load_labels(path, source, max_labels=4, max_label_records=128):
    """Read a bounded label prefix; source/frame/timestamp all identify a target."""
    labels = []
    keys = set()
    with Path(path).open(encoding="utf-8-sig") as stream:
        for line_number, line in enumerate(islice(stream, max_label_records), 1):
            if not line.strip():
                continue
            record = json.loads(line)
            if Path(record["source"]).resolve() != Path(source).resolve():
                raise ValueError(f"label {line_number}: source mismatch")
            if (record.get("schema_version") != 1 or record.get("coordinate_frame") != "world_xy"
                    or record.get("yaw_unit") != "radians"
                    or record.get("label_type") not in ("manual_desired_pose", "motor_cut_trajectory_goal")):
                raise ValueError(f"label {line_number}: unsupported schema")
            frame, timestamp = record["frame"], record["timestamp"]
            for name in ("robot_pose_world", "desired_goal_world"):
                if not all(math.isfinite(record[name][key]) for key in ("x", "y", "yaw")):
                    raise ValueError(f"label {line_number}: invalid pose")
            if isinstance(frame, bool) or not isinstance(frame, int) or frame < 1 or not math.isfinite(timestamp):
                raise ValueError(f"label {line_number}: invalid frame/timestamp")
            if frame in keys:
                raise ValueError(f"label {line_number}: duplicate frame")
            if record["label_type"] == "motor_cut_trajectory_goal":
                provenance = record.get("provenance", {})
                motor, target_motor = record.get("motor_cut", {}), provenance.get("target_motor_cut", {})
                if (provenance.get("method") != "future_active_trajectory_distance"
                        or provenance.get("target_frame", 0) <= frame
                        or not math.isfinite(provenance.get("target_timestamp", float("nan")))
                        or provenance["target_timestamp"] <= timestamp
                        or not all(math.isfinite(m.get("rpm", float("nan"))) and abs(m["rpm"]) > 0
                                   for m in (motor, target_motor))
                        or motor.get("active_since") is None
                        or motor["active_since"] != target_motor.get("active_since")):
                    raise ValueError(f"label {line_number}: invalid motor trajectory provenance")
            keys.add(frame)
            labels.append(record)
    labels.sort(key=lambda r: r["frame"])
    if not labels:
        raise ValueError("no labels in the bounded label prefix")
    return labels[:max_labels]


def prepare(source, labels_path, output, config, max_records=15000, max_frames=800,
            max_labels=4, max_label_records=128, max_candidates=1024, pose_max_gap_s=.1,
            verified_start_radius=None):
    # Reuse the replay's timestamp alignment, extrinsics and +pi/2 heading.
    from replay_boundary import iter_data_package, update_exploration

    if min(max_records, max_frames, max_labels, max_label_records, max_candidates) < 1:
        raise ValueError("data budgets must be positive")
    if Path(output).resolve() in (Path(source).resolve(), Path(labels_path).resolve()):
        raise ValueError("output must differ from input files")
    if verified_start_radius is not None and (not math.isfinite(verified_start_radius) or verified_start_radius <= 0):
        raise ValueError("verified_start_radius must be finite and positive")
    labels = load_labels(labels_path, source, max_labels, max_label_records)
    pending = {r["frame"]: r for r in labels}
    explorer = BoundaryExplorer(config)
    alignment = {}
    episodes, skipped = [], []
    frames_read = 0
    stream = iter_data_package(Path(source), max_records, pose_max_gap_s, alignment)
    try:
        for number, frame in enumerate(islice(stream, min(max_frames, max(pending))), 1):
            frames_read = number
            if number == 1 and verified_start_radius is not None:
                explorer.seed_verified_grass_disk(frame.robot_xyz[:2], verified_start_radius)
            result = update_exploration(explorer, frame)
            if number not in pending:
                continue
            label = pending.pop(number)
            pose = (float(frame.robot_xyz[0]), float(frame.robot_xyz[1]), float(frame.robot_yaw + math.pi/2))
            labelled_pose = tuple(label["robot_pose_world"][key] for key in ("x", "y", "yaw"))
            distance, yaw = pose_errors([pose], labelled_pose)
            if abs(frame.timestamp - label["timestamp"]) > 1e-4 or distance[0] > .001 or yaw[0] > .001:
                raise ValueError(f"frame {number}: label alignment mismatch; use original replay loading options")
            candidates = explorer.goal_candidates(pose)
            if not candidates:
                skipped.append(dict(frame=number, reason="no baseline-positive safe candidates", status=result.status))
                continue
            # Hard priority matches production; target never affects pruning.
            priority = [c for c in candidates if c.boundary_gain > 0]
            eligible = priority or candidates
            eligible.sort(key=lambda c: (c.baseline_score, -c.path_cost, c.cell), reverse=True)
            retained = eligible[:max_candidates]
            desired = [label["desired_goal_world"][k] for k in ("x", "y", "yaw")]
            all_rewards = rewards([c.pose for c in eligible], desired)
            episodes.append(dict(frame=number, timestamp=frame.timestamp, desired_pose=desired,
                label_type=label["label_type"], label_provenance=label.get("provenance"),
                candidates=[asdict(c) for c in retained], eligible_count=len(eligible),
                safe_candidate_count=len(candidates), oracle_all_reward=float(all_rewards.max()),
                logged_algorithm_goal=label.get("algorithm_goal_world"),
                replay_baseline_goal=list(result.goal_pose) if result.goal_pose is not None else None))
    finally:
        stream.close()
    skipped.extend(dict(frame=n, reason="outside raw-record/frame budget") for n in sorted(pending))
    record = dict(schema_version=2, task="label_reward_contextual_bandit", source=str(Path(source).resolve()),
        labels_source=str(Path(labels_path).resolve()), exploration_config=asdict(config),
        pose_max_gap_s=pose_max_gap_s, verified_start_radius=verified_start_radius,
        budgets=dict(max_records=max_records, max_frames=max_frames, max_labels=max_labels,
            max_label_records=max_label_records, max_candidates=max_candidates),
        frames_read=frames_read, alignment=alignment, skipped=skipped, episodes=episodes)
    write_json(output, record)
    return dict(dataset=str(output), frames_read=frames_read, episodes=len(episodes), skipped=skipped,
                aligned_frames=alignment["aligned_frames"], raw_records_read=alignment.get("raw_records_read"),
                raw_bytes_read=alignment.get("raw_bytes_read"))


def load_dataset(path):
    record = json.loads(Path(path).read_text(encoding="utf-8"))
    if record.get("schema_version") != 2 or record.get("task") != "label_reward_contextual_bandit":
        raise ValueError("incompatible training dataset; regenerate with prepare for map-boundary features v2")
    episodes = sorted(record["episodes"], key=lambda e: e["timestamp"])
    if not episodes:
        raise ValueError("no usable episodes; increase bounded budgets or check safety/configuration")
    return record, episodes


def episode_arrays(episode, position_scale=1., yaw_scale=1.):
    candidates = [GoalScoreCandidate(**c) for c in episode["candidates"]]
    if not candidates:
        raise ValueError("episode has no actions")
    x = np.array([features(c) for c in candidates])
    baseline = np.array([c.baseline_score for c in candidates])
    if (baseline <= 0).any() or not np.isfinite(baseline).all():
        raise ValueError("invalid baseline scores")
    r = rewards([c.pose for c in candidates], episode["desired_pose"], position_scale, yaw_scale)
    return x, np.log(baseline), r


class GoalScoreBanditEnv:
    """Gym-style reset/step interface, variable safe-action sets, one-step episodes.

    Labels stay inside the reward function; observations contain only geometry
    and baseline logits. An invalid action raises instead of executing a pose.
    """

    def __init__(self, episodes, position_scale=1., yaw_scale=1.):
        if not episodes:
            raise ValueError("environment needs labelled episodes")
        self.episodes = episodes
        self.position_scale, self.yaw_scale = position_scale, yaw_scale
        self._index = -1
        self._done = True

    def reset(self, *, episode_index=None):
        index = (self._index + 1) % len(self.episodes) if episode_index is None else episode_index
        if isinstance(index, bool) or not isinstance(index, int) or not 0 <= index < len(self.episodes):
            raise ValueError("invalid episode index")
        self._index = index
        x, base, self._rewards = episode_arrays(self.episodes[index], self.position_scale, self.yaw_scale)
        self._observation = dict(features=x, baseline_logits=base, action_mask=np.ones(len(base), dtype=bool))
        self._done = False
        return self._observation, dict(frame=self.episodes[index]["frame"])

    def step(self, action):
        if self._done:
            raise RuntimeError("call reset before step")
        if isinstance(action, bool) or not isinstance(action, (int, np.integer)) or not 0 <= action < len(self._rewards):
            raise ValueError("action outside safe candidate set")
        self._done = True
        episode = self.episodes[self._index]
        return self._observation, float(self._rewards[action]), True, False, dict(
            frame=episode["frame"], selected_pose=episode["candidates"][action]["pose"])


def bandit_gradient(weights, x, baseline_logits, reward, temperature=1., kl_weight=.02):
    """Exact E[(R-E[R]) grad log pi], with KL(pi || baseline) regularization."""
    raw = x @ weights
    logits = (baseline_logits + np.clip(raw, -8, 8)) / temperature
    logits -= logits.max()
    p = np.exp(logits)
    p /= p.sum()
    log_q = baseline_logits / temperature
    log_q -= np.logaddexp.reduce(log_q)
    log_p = logits - np.logaddexp.reduce(logits)
    advantage = reward - kl_weight * (log_p - log_q)
    advantage -= p @ advantage
    gradient = x.T @ (p * advantage * (np.abs(raw) < 8)) / temperature
    return gradient, float(p @ reward)


def split_episodes(episodes, train_fraction=.75, gap_s=1.):
    if not math.isfinite(gap_s) or gap_s < 0 or not 0 < train_fraction < 1:
        raise ValueError("invalid chronological split settings")
    if len(episodes) < 2:
        raise ValueError("at least two usable labels needed for train/validation")
    cut = min(len(episodes)-1, max(1, int(len(episodes)*train_fraction)))
    train = episodes[:cut]
    # Trajectory targets use future observations as supervision. Validation
    # must start after that evidence, even when the requested gap is smaller.
    target_times = [(e.get("label_provenance") or {})["target_timestamp"]
                    for e in train if e.get("label_type") == "motor_cut_trajectory_goal"]
    evidence_end = max(target_times) if target_times else None
    validation = [e for e in episodes[cut:]
                  if e["timestamp"] - train[-1]["timestamp"] >= gap_s
                  and (evidence_end is None or e["timestamp"] > evidence_end)]
    if not validation:
        if evidence_end is not None:
            raise ValueError("validation empty after trajectory target horizon/time gap; add later labels or more data")
        raise ValueError("validation empty after time gap; add labels or explicitly reduce --split-gap-s")
    return train, validation


def evaluate(episodes, policy, position_scale=1., yaw_scale=1.):
    rows = []
    for e in episodes:
        x, base, r = episode_arrays(e, position_scale, yaw_scale)
        learned = base + np.clip(x @ policy.weights, -8, 8)
        def best_index(scores):
            return max(range(len(scores)), key=lambda i: (scores[i],
                -e["candidates"][i]["path_cost"], tuple(e["candidates"][i]["cell"])))
        baseline_index, selected = best_index(base), best_index(learned)
        poses = [c["pose"] for c in e["candidates"]]
        distance, yaw = pose_errors(poses, e["desired_pose"])
        row = dict(frame=e["frame"], baseline_reward=float(r[baseline_index]),
            policy_reward=float(r[selected]), oracle_reward=float(r.max()),
            baseline_position_error_m=float(distance[baseline_index]),
            policy_position_error_m=float(distance[selected]), baseline_yaw_error_rad=float(yaw[baseline_index]),
            policy_yaw_error_rad=float(yaw[selected]), selected_pose=poses[selected],
            action_count=len(poses), eligible_count=e["eligible_count"],
            candidate_set_truncated=len(poses) < e["eligible_count"])
        for prefix, goal in (("logged", e.get("logged_algorithm_goal")), ("replay", e.get("replay_baseline_goal"))):
            if isinstance(goal, dict):
                goal = [goal[k] for k in ("x", "y", "yaw")]
            row[prefix + "_reward"] = (float(rewards([goal], e["desired_pose"], position_scale, yaw_scale)[0])
                                        if goal is not None else None)
        rows.append(row)
    keys = ("baseline_reward", "policy_reward", "oracle_reward", "baseline_position_error_m",
            "policy_position_error_m", "baseline_yaw_error_rad", "policy_yaw_error_rad")
    return dict(episodes=len(rows), means={key: float(np.mean([r[key] for r in rows])) for key in keys}, rows=rows)


def train(dataset, model_path, report_path, epochs=300, learning_rate=.1, temperature=1.,
          kl_weight=.02, l2=.001, train_fraction=.75, split_gap_s=1., position_scale=1., yaw_scale=1.):
    if (epochs < 1 or not all(math.isfinite(v) and v > 0 for v in (learning_rate, temperature))
            or not all(math.isfinite(v) and v >= 0 for v in (kl_weight, l2))):
        raise ValueError("invalid optimizer settings")
    paths = [Path(p).resolve() for p in (dataset, model_path, report_path)]
    if len(set(paths)) != 3:
        raise ValueError("dataset, model and report paths must differ")
    record, episodes = load_dataset(dataset)
    training, validation = split_episodes(episodes, train_fraction, split_gap_s)
    arrays = [episode_arrays(e, position_scale, yaw_scale) for e in training]
    policy = GoalScorePolicy()
    # Fixed epochs and train-only updates: validation never selects a checkpoint.
    for _ in range(epochs):
        gradient = np.mean([bandit_gradient(policy.weights, *a, temperature, kl_weight)[0]
                            for a in arrays], axis=0) - l2 * policy.weights
        policy.weights += learning_rate * gradient
        policy.weights[7] = max(0.0, policy.weights[7])
    metadata = dict(dataset=str(Path(dataset).resolve()), exploration_config=record["exploration_config"],
        training_frames=[e["frame"] for e in training], validation_frames=[e["frame"] for e in validation],
        epochs=epochs, learning_rate=learning_rate, temperature=temperature, kl_weight=kl_weight, l2=l2,
        split_gap_s=split_gap_s, position_scale=position_scale, yaw_scale=yaw_scale)
    policy.save(model_path, metadata)
    report = dict(task="single_step_label_reward_bandit", metadata=metadata,
        train=evaluate(training, policy, position_scale, yaw_scale),
        validation=evaluate(validation, policy, position_scale, yaw_scale),
        limitations=["Label reward does not measure closed-loop exploration success.",
                    "Chronological holdout from one log remains correlated; use separate logs for final testing.",
                    "Candidate headings use nearby accumulated-map boundary tangents when reliable; hard boundary priority remains fixed.",
                    "Baseline means full-search ranking; logged/replay rewards compare the staged original planner.",
                    "Training candidate cap can omit the optimum; inference searches all eligible candidates."])
    write_json(report_path, report)
    return dict(model=str(model_path), report=str(report_path), train=report["train"]["means"],
                validation=report["validation"]["means"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    p = commands.add_parser("prepare", help="bounded streaming map replay + labelled safe action sets")
    p.add_argument("--source", type=Path, required=True)
    p.add_argument("--labels", type=Path, required=True)
    p.add_argument("--output", type=Path, default=Path("rl_artifacts/dataset.json"))
    for name, default in (("max-records", 15000), ("max-frames", 800), ("max-labels", 4),
                          ("max-label-records", 128), ("max-candidates", 1024)):
        p.add_argument("--" + name, type=int, default=default)
    p.add_argument("--robot-radius", type=float, default=.2)
    p.add_argument("--sensor-range", type=float, default=2.)
    p.add_argument("--resolution", type=float, default=.1)
    p.add_argument("--config", type=Path, help="JSON ExplorationConfig; use identical replay settings")
    p.add_argument("--pose-max-gap-s", type=float, default=.1)
    p.add_argument("--verified-start-radius", type=float)
    p = commands.add_parser("train")
    p.add_argument("--dataset", type=Path, default=Path("rl_artifacts/dataset.json"))
    p.add_argument("--model", type=Path, default=Path("rl_artifacts/goal_score_model.json"))
    p.add_argument("--report", type=Path, default=Path("rl_artifacts/training_report.json"))
    p.add_argument("--epochs", type=int, default=300)
    for name, default in (("learning-rate", .1), ("temperature", 1.), ("kl-weight", .02),
                          ("l2", .001), ("train-fraction", .75), ("split-gap-s", 1.),
                          ("position-scale", 1.), ("yaw-scale", 1.)):
        p.add_argument("--" + name, type=float, default=default)
    p = commands.add_parser("evaluate", help="evaluate a saved policy on a separately prepared dataset")
    p.add_argument("--dataset", type=Path, required=True)
    p.add_argument("--model", type=Path, required=True)
    p.add_argument("--output", type=Path, default=Path("rl_artifacts/evaluation.json"))
    p.add_argument("--position-scale", type=float, default=1.)
    p.add_argument("--yaw-scale", type=float, default=1.)
    args = vars(parser.parse_args())
    command = args.pop("command")
    try:
        if command == "prepare":
            config_path = args.pop("config")
            config = dict(robot_radius=args.pop("robot_radius"), sensor_range=args.pop("sensor_range"),
                          resolution=args.pop("resolution"))
            if config_path:
                config = json.loads(config_path.read_text(encoding="utf-8"))
            result = prepare(labels_path=args.pop("labels"), config=ExplorationConfig(**config), **args)
        elif command == "train":
            result = train(model_path=args.pop("model"), report_path=args.pop("report"), **args)
        else:
            dataset, model, output = (args.pop(k) for k in ("dataset", "model", "output"))
            if Path(output).resolve() in (dataset.resolve(), model.resolve()):
                raise ValueError("evaluation output must differ from inputs")
            _, episodes = load_dataset(dataset)
            result = evaluate(episodes, GoalScorePolicy.load(model), **args)
            write_json(output, result)
            result = dict(report=str(output), episodes=result["episodes"], means=result["means"])
    except (ValueError, KeyError, OSError) as error:
        parser.error(str(error))
    print(json.dumps(result, ensure_ascii=False, allow_nan=False))


if __name__ == "__main__":
    main()
